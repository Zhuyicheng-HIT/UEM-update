#!/usr/bin/env bash
set -euo pipefail

if [[ "$#" -ne 4 ]]; then
  echo "Usage: $0 CONFIG_PATH CKPT_PATH EULER_STEPS EVAL_SUFFIX" >&2
  exit 2
fi

CONFIG_PATH="$1"
CKPT_PATH="$2"
EULER_STEPS="$3"
EVAL_SUFFIX="$4"
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$PROJECT_ROOT"
export PYTHONPATH="$PROJECT_ROOT${PYTHONPATH:+:$PYTHONPATH}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}"
PYTHON_BIN="${PYTHON_BIN:-python}"
EVAL_OVERRIDES=()
if [[ -n "${EVAL_NUM_GPUS:-}" ]]; then
  EVAL_OVERRIDES+=(EVAL.NUM_GPUS "$EVAL_NUM_GPUS")
fi

"$PYTHON_BIN" eval/eval_exp.py \
  CONFIG "$CONFIG_PATH" \
  MODEL.CKPT_PATH "$CKPT_PATH" \
  FLOW.NUM_STEPS "$EULER_STEPS" \
  TRAIN.EVAL_SUFFIX "$EVAL_SUFFIX" \
  "${EVAL_OVERRIDES[@]}"
